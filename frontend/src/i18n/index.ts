const DICTS: Record<Language, Dict> = { en, hi, mr }
export const LANGUAGES: { code: Language; label: string; native: string }[] = [
  { code: 'en', label: 'English', native: 'English' },
  { code: 'hi', label: 'Hindi', native: 'हिन्दी' },
  { code: 'mr', label: 'Marathi', native: 'मराठी' },
]

interface I18nCtx {
  lang: Language
  setLang: (l: Language) => void
  t: (key: string) => string
}

const Ctx = createContext<I18nCtx>({ lang: 'en', setLang: () => {}, t: (k) => en[k] ?? k })
const LANG_KEY = 'cove2e.lang'

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const { user } = useAuth()
  const [lang, setLangState] = useState<Language>(() => (localStorage.getItem(LANG_KEY) as Language) || 'en')

  useEffect(() => {
    if (user?.preferred_language && !localStorage.getItem(LANG_KEY)) setLangState(user.preferred_language as Language)
  }, [user])

  const setLang = useCallback(
    (l: Language) => {
      setLangState(l)
      localStorage.setItem(LANG_KEY, l)
      document.documentElement.lang = l
      if (user) api.setLanguage(l).catch(() => {})
    },
    [user],
  )

  const t = useCallback((key: string) => DICTS[lang][key] ?? en[key] ?? key, [lang])
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t])
  return React.createElement(Ctx.Provider, { value }, children)
}

export function useI18n() {
  return useContext(Ctx)
}
